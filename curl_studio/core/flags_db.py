CURL_FLAGS_MAP: Dict[str, CurlFlagInfo] = {f.flag_id: f for f in CURL_FLAGS_DB}


def search_flags(query: str = "", category: str = "ALL") -> List[CurlFlagInfo]:
    """Filters the 18 common flags by keyword and/or category."""
    q = query.strip().lower()
    cat = category.strip()
    results: List[CurlFlagInfo] = []
    for f in CURL_FLAGS_DB:
        if cat and cat not in ("ALL", "All Categories") and f.category.lower() != cat.lower():
            continue
        hay = f"{f.short} {f.long} {f.category} {f.summary} {f.detail} {f.example} {f.trainee_tip}".lower()
        if q and q not in hay:
            continue
        results.append(f)
    return results
